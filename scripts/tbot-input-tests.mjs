import assert from 'node:assert/strict';
import {classifyHand} from '../lib/tbot/gesture.ts';
import {classifyTabletZone,stableTabletDirection} from '../lib/tbot/tablet-gesture.ts';
const hand=(fingers,x=.5)=>{const lm=Array.from({length:21},()=>({x:.5,y:.5,z:0}));for(let n=0;n<4;n++){const i=[8,12,16,20][n];lm[i].y=fingers[n]?.2:.8;lm[i-2].y=.5}lm[9].x=x;return lm};
assert.equal(classifyHand(undefined).linear,0);
assert.equal(classifyHand(hand([1,1,1,1])).linear,0);
assert.equal(classifyHand(hand([1,0,0,0])).linear,.07);
assert.equal(classifyHand(hand([1,0,0,0],.8)).angular,.35);
assert.equal(classifyHand(hand([1,0,0,0],.2)).angular,-.35);
assert.equal(classifyHand(hand([1,1,0,0])).linear,-.05);
assert.equal(classifyHand(hand([0,1,0,1])).linear,0);
assert.equal(classifyTabletZone(.5,.5),'stop');
assert.equal(classifyTabletZone(.5,.04),'stop');
assert.equal(classifyTabletZone(.5,.2),'forward');
assert.equal(classifyTabletZone(.5,.8),'backward');
assert.equal(classifyTabletZone(.2,.5),'left');
assert.equal(classifyTabletZone(.8,.5),'right');
let state={candidate:'stop',frames:0,output:'stop'};
for(let i=0;i<3;i++)state=stableTabletDirection(state.candidate,state.frames,'forward');
assert.equal(state.output,'stop');state=stableTabletDirection(state.candidate,state.frames,'forward');assert.equal(state.output,'forward');
console.log('15 gesture and tablet dead-zone checks passed.');
